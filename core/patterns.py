"""
Регулярные выражения и шаблоны поиска персональных и корпоративных данных.
Поддерживает поиск:
- Телефоны (+7, 7, 8, сотовые и стационарные, с разделителями и слитные)
- Email
- ИНН (10 и 12 знаков)
- ОГРН / ОГРНИП
- КПП
- БИК
- Банковские счета (Р/С, К/С)
- Банковские карты (МИР, Visa, Mastercard)
- Паспорта РФ
- СНИЛС
- Водительские удостоверения
- Организации (ООО, АО, ПАО, ИП и др.)
- Почтовые адреса и индексы
"""

import re

# Email
EMAIL_PATTERN = re.compile(
    r'\b[A-Za-z0-9._%+-]+@[A-Za-z0-9.-]+\.[A-Z|a-z]{2,7}\b'
)

# Российские телефонные номера (слитные 11 цифр или с разделителями)
# Примеры: +79001234567, 89001234567, +7(900) 123-45-67, +7 (900) 123-45-67, 8-900-123-45-67
STRICT_PHONE_PATTERN = re.compile(
    r'(?:(?:\+?7|8)[\s\-]*(?:\(\d{3}\)|\d{3})[\s\-]*\d{3}[\s\-]?\d{2}[\s\-]?\d{2}\b|\b(?:\+?7|8)\d{10}\b)'
)

PHONE_PATTERN = re.compile(
    r'(?:(?:\+?7|8)[\s\-]?)?(?:\(?\d{3,5}\)?[\s\-]?)?\d{2,3}[\s\-]?\d{2}[\s\-]?\d{2}\b'
)

# СНИЛС: 123-456-789 01 или 123 456 789 01 или 12345678901
SNILS_PATTERN = re.compile(
    r'\b\d{3}[-\s]\d{3}[-\s]\d{3}[-\s]\d{2}\b|\b\d{11}\b'
)

# Паспорт РФ: 4 цифры серии и 6 цифр номера (с префиксом серии и любым порядком)
PASSPORT_PATTERN = re.compile(
    r'(?:'
    r'(?:серия\b[:\s]*)?(?:\d{2}\s*\d{2}|\d{4})\s*(?:№\s*|номер\s*)?\d{6}\b'
    r'|'
    r'(?:№\s*|номер\s*)\d{6}\s*(?:,?\s*серия\b[:\s]*)?(?:\d{2}\s*\d{2}|\d{4})\b'
    r')',
    re.IGNORECASE
)

# Раздельные поля паспорта (для отдельных ячеек таблиц)
CONTEXT_PASSPORT_SERIES = re.compile(
    r'\b(?:серия(?:\s+паспорта)?)\b[:\s]+(\d{2}\s*\d{2}|\d{4})\b',
    re.IGNORECASE
)
CONTEXT_PASSPORT_NUMBER = re.compile(
    r'\b(?:номер(?:\s+паспорта)?)\b[:\s]+(\d{6})\b',
    re.IGNORECASE
)

# ИНН: 10 цифр (ЮЛ) или 12 цифр (ФЛ/ИП)
INN_PATTERN = re.compile(
    r'\b\d{10}\b|\b\d{12}\b'
)

# ОГРН: 13 цифр, ОГРНИП: 15 цифр
OGRN_PATTERN = re.compile(
    r'\b\d{13}\b|\b\d{15}\b'
)

# КПП: 9 цифр/символов
KPP_PATTERN = re.compile(
    r'\b\d{4}[0-9A-Z]{2}\d{3}\b'
)

# Общий шаблон для КПП рядом с контекстом: "КПП: 770101001"
CONTEXT_KPP_PATTERN = re.compile(
    r'\b(?:КПП|кпп)[\s:]*([0-9]{4}[0-9A-Za-z]{2}[0-9]{3})\b'
)

# БИК: 9 цифр, начинающихся на 04
BIK_PATTERN = re.compile(
    r'\b04\d{7}\b'
)

# Банковский расчетный/корр счет: 20 цифр
BANK_ACCOUNT_PATTERN = re.compile(
    r'\b(?:30101|30102|40701|40702|40703|40802|40817|40820|40502|40602|42301|42302|42303|42304|42305|42306|42307|40807|40911|47422|47423|40101|40102)\d{15}\b'
)

# Банковские карты: 16-19 цифр (разделены пробелом, дефисом или слитно)
CREDIT_CARD_PATTERN = re.compile(
    r'\b(?:\d{4}[-\s]?){3}\d{4}\b|\b(?:\d{4}[-\s]?){3}\d{7}\b'
)

# Названия организаций (с ОПФ):
# Примеры: ООО "Рога и Копыта", АО «Северсталь», ПАО «Газпром», ИП Иванов И.И.
ORG_PREFIXES = r'(?:ООО|АО|ЗАО|ПАО|ОАО|ИП|НКО|МУП|ГУП|ГБУ|АНО|НП|КФХ|ФГУП|МАОУ|МБОУ|МБУ|СПК|ТСЖ|СНТ)'

ORG_PATTERN_QUOTED = re.compile(
    rf'\b{ORG_PREFIXES}\s*(?:[«"“][^»"”\n\r]{{2,120}}[»"”](?:[»"”])?)',
    re.IGNORECASE
)
ORG_PATTERN_UNQUOTED = re.compile(
    rf'\b{ORG_PREFIXES}\s+([A-ZА-ЯЁ][A-Za-zА-Яа-яЁё0-9\-\s]{{2,40}}?)(?=[,\.;\n\r]|\s+(?:ИНН|ОГРН|КПП|в\s+лице|действующ|г\.|ул\.)|\s*$)',
    re.IGNORECASE
)

# Горизонтальный пробел (исключает переводы строк \n и \r для предотвращения объединения строк)
_H_SPACE = r'[^\S\r\n]'

# 1. ФИО из 3 слов (Иванов Иван Иванович, Петров Петр Петрович)
FIO_FULL_PATTERN = re.compile(
    rf'\b([А-ЯЁ][а-яё]+(?:-[А-ЯЁ][а-яё]+)?){_H_SPACE}+([А-ЯЁ][а-яё]+){_H_SPACE}+([А-ЯЁ][а-яё]+(?:ич|на|ович|евич|овна|евна|ична|ыч|овича|евича|овичу|евичу|овичем|евичем|овиче|евиче|овны|евны|овне|евне|овну|евну|овной|евной|ичны|ичне|ичну|ичной|ича|ичу|ичем|иче))\b'
)

# 2. ФИО с инициалами (все комбинации)
# Иванов И.И., Иванов И. И., Иванов И., Иванов И.И
FIO_SURNAME_INITIALS = re.compile(
    rf'\b([А-ЯЁ][а-яё]{{1,25}}(?:-[А-ЯЁ][а-яё]{{1,25}})?){_H_SPACE}+([А-ЯЁ]\.(?:{_H_SPACE}*[А-ЯЁ]\.)?|[А-ЯЁ]\.[А-ЯЁ])(?!\w)'
)

# И.И. Иванов, И. И. Иванов, И.И.Иванов, И. Иванов
FIO_INITIALS_SURNAME = re.compile(
    rf'\b([А-ЯЁ]\.(?:{_H_SPACE}*[А-ЯЁ]\.)?){_H_SPACE}*([А-ЯЁ][а-яё]{{1,25}}(?:-[А-ЯЁ][а-яё]{{1,25}})?)\b'
)

# Иванов Иван И., Иванов Иван И.И., Иванов Иван И. И.
FIO_NAME_INITIALS = re.compile(
    rf'\b([А-ЯЁ][а-яё]{{1,25}}){_H_SPACE}+([А-ЯЁ][а-яё]{{1,25}}){_H_SPACE}+([А-ЯЁ]\.(?:{_H_SPACE}*[А-ЯЁ]\.)?)(?!\w)'
)

# Иван И. Иванов, Иван И.И. Иванов
FIO_INITIALS_MIDDLE = re.compile(
    rf'\b([А-ЯЁ][а-яё]{{1,25}}){_H_SPACE}+([А-ЯЁ]\.(?:{_H_SPACE}*[А-ЯЁ]\.)?){_H_SPACE}+([А-ЯЁ][а-яё]{{1,25}})\b'
)

# Иванов И. Иванович, Иванов И.Иванович
FIO_SURNAME_INIT_PATR = re.compile(
    rf'\b([А-ЯЁ][а-яё]{{1,25}}){_H_SPACE}+([А-ЯЁ]\.){_H_SPACE}*([А-ЯЁ][а-яё]{{2,25}}(?:ович|евич|овна|евна|ична|инична|овича|евича|ича|овичу|евичу|ичу|овичем|евичем|ичем|овиче|евиче|иче|овны|евны|ичны|овне|евне|ичне|овну|евну|ичну|овной|евной|ичной))\b'
)

# 3. ФИО из 2 слов (Иванов Иван, Иван Иванов)
FIO_2_WORDS_PATTERN = re.compile(
    rf'\b([А-ЯЁ][а-яё]{{2,25}}){_H_SPACE}+([А-ЯЁ][а-яё]{{2,25}})\b'
)

# 4. Двойные/составные фамилии через дефис (Мамин-Сибиряк, Салтыков-Щедрин)
DOUBLE_SURNAME_PATTERN = re.compile(
    r'\b([А-ЯЁ][а-яё]{1,25}-[А-ЯЁ][а-яё]{1,25})\b'
)

# 5. Короткие фамилии (2-3 буквы)
SHORT_SURNAMES_PATTERN = re.compile(
    r'\b(Ким|Пак|Ли|Цой|Ван|Цай|Хан|Югай|Чен|Дуб|Рысь|Грач|Жук|Волк|Кот|Сокол|Борщ)\b'
)

# 6. Отчества отдельно (Иванович, Сергеевна, Ивановичу и др.)
PATRONYMIC_PATTERN = re.compile(
    r'\b([А-ЯЁ][а-яё]{2,25}(?:ович|евич|овна|евна|ична|инична|овича|евича|ича|овичу|евичу|ичу|овичем|евичем|ичем|овиче|евиче|иче|овны|евны|ичны|овне|евне|ичне|овну|евну|ичну|овной|евной|ичной|иничны|иничне|иничну|иничной))\b'
)

# 7. Фамилии после ключевых слов и должностей (Заявитель: Иванов, Собственник: Козлов и т.д.)
# Префикс должности нечувствителен к регистру, но фамилия СТРОГО с заглавной буквы
_ROLE_WORDS = (
    r'заявитель|собственник|инженер|прораб|мастер|директор|исполнитель|техник|'
    r'представитель|составил|сдал|принял|устранил|руководитель|начальник|'
    r'бригадир|монтажник|слесарь|эксперт|специалист|бухгалтер|секретарь|'
    r'фамилия|гр|гражданин|гражданка|от'
)
CONTEXT_SURNAME_PATTERN = re.compile(
    rf'\b(?:(?i:{_ROLE_WORDS})){_H_SPACE}*[:\-/]?{_H_SPACE}*'
    rf'([А-ЯЁ][а-яё]{{1,25}}(?:-[А-ЯЁ][а-яё]{{1,25}})?)\b'
)

# 8. Фамилия в подписи: Подпись: / Иванов / или Подпись: Иванов
SIGNATURE_SURNAME_PATTERN = re.compile(
    rf'(?:(?i:подпись|м\.п\.)){_H_SPACE}*[:\-/]?{_H_SPACE}*[/_]?{_H_SPACE}*'
    rf'([А-ЯЁ][а-яё]{{1,25}}(?:-[А-ЯЁ][а-яё]{{1,25}})?){_H_SPACE}*[/_]?'
)

# 9. Морфологические русские фамилии на стандартные окончания (-ов, -ев, -ин, -ын, -ский, -цкий, -их)
SURNAME_MORPH_PATTERN = re.compile(
    r'\b([А-ЯЁ][а-яё]{2,22}(?:'
    r'ов|ова|ову|овым|ове|'
    r'ев|ева|еву|евым|еве|'
    r'ёв|ёва|ёву|ёвым|ёве|'
    r'ин|ина|ину|иным|ине|'
    r'ын|ына|ыну|ыным|ыне|'
    r'ский|ского|скому|ским|ском|ская|ской|скую|ские|ских|скими|'
    r'цкий|цкого|цкому|цким|цком|цкая|цкой|цкую|цкие|цких|цкими|'
    r'их|ых))\b'
)

# Совместимость со старыми переменными
FIO_INITIALS_PATTERN = FIO_SURNAME_INITIALS
INITIALS_FIO_PATTERN = FIO_INITIALS_SURNAME

# Почтовый индекс РФ (6 цифр, не внутри кадастровых номеров или шифров)
POSTAL_CODE_PATTERN = re.compile(
    r'(?<![\d:\-\/\w])([1-6]\d{5})(?![\d:\-\/\w])'
)

# Полный адресный паттерн (комплексный, региональный, городской и уличный)
ADDRESS_PATTERN = re.compile(
    r'(?:'
    # 1. Комплексный адрес: индекс/страна/регион/город + улица + дом (+ корпус/кв)
    r'(?:\b(?:\d{6}[,\s]+)?'
    r'(?:(?:Российская\s+Федерация|РФ|Россия)[,\s]+)?'
    r'(?:[А-ЯЁ][а-яё\-]+\s+(?:обл\b\.?|область|край|район)[,\s]*)?'
    r'(?:(?:г\b\.?|город|пос\b\.?|п\b\.?|село|с\.\s*|дер\b\.?)\s+[А-ЯЁ][а-яё\-]+[,\s]*)?'
    r'(?:(?:ул\b\.?|улица|пр-кт|проспект|пер\b\.?|переулок|ш\b\.?|шоссе|бул\b\.?|бульвар|наб\b\.?|набережная)\s+[А-ЯЁа-яё0-9\-\s]+[,\s]*)'
    r'(?:(?:д\b\.?|дом)\s*\d+[\w/]*[,\s]*)'
    r'(?:(?:к\b\.?|корп\b\.?|корпус|стр\b\.?|строение)\s*\d+[\w/]*[,\s]*)?'
    r'(?:(?:кв\b\.?|квартира|оф\b\.?|офис|пом\b\.?)\s*\d+[\w/]*\b)?)'
    r'|'
    # 2. Населенный пункт + улица + дом (+ корпус/кв)
    r'(?:\b(?:г\b\.?|город|пос\b\.?|п\b\.?|село|с\.\s*|дер\b\.?)\s+[А-ЯЁ][а-яё\-]+[,\s]+'
    r'(?:ул\b\.?|улица|пр-кт|проспект|пер\b\.?|переулок|ш\b\.?|шоссе|бул\b\.?|бульвар|наб\b\.?|набережная)\s+[А-ЯЁа-яё0-9\-\s]+[,\s]+'
    r'(?:(?:д\b\.?|дом)\s*)?\d+[\w/]*'
    r'(?:[,\s]+(?:к\b\.?|корп\b\.?|корпус|стр\b\.?|строение)\s*\d+[\w/]*)?'
    r'(?:[,\s]+(?:кв\b\.?|квартира|оф\b\.?|офис|пом\b\.?)\s*\d+[\w/]*)?)'
    r'|'
    # 3. Улица + дом (+ корпус/кв)
    r'(?:\b(?:ул\b\.?|улица|пр-кт|проспект|пер\b\.?|переулок|ш\b\.?|шоссе|бульвар|бул\b\.?|набережная|наб\b\.?)\s+[А-ЯЁа-яё0-9\-\s]+[,\s]+'
    r'(?:(?:д\b\.?|дом)\s*)?\d+[\w/]*'
    r'(?:[,\s]+(?:к\b\.?|корп\b\.?|корпус|стр\b\.?|строение)\s*\d+[\w/]*)?'
    r'(?:[,\s]+(?:кв\b\.?|квартира|оф\b\.?|офис|пом\b\.?)\s*\d+[\w/]*)?)'
    r'|'
    # 4. д. X, кв. Y
    r'(?:\b(?:д\b\.?|дом)\s*\d+[\w/]*[,\s]+(?:кв\b\.?|квартира|оф\b\.?|офис)\s*\d+[\w/]*)'
    r')',
    re.IGNORECASE
)
